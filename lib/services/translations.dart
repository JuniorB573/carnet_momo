/// Notifie tous les écrans quand la langue change, et sauvegarde le choix
/// pour qu'il soit conservé au prochain lancement de l'app.
class LanguageController extends ValueNotifier<String> {
  LanguageController() : super('fr') {
    _load();
  }

  Future<void> _load() async {
    final prefs = await SharedPreferences.getInstance();
    final saved = prefs.getString('language') ?? 'fr';
    // Filet de sécurité : si une ancienne installation avait choisi le fon
    // (langue retirée), on retombe proprement sur le français.
    value = kTranslations.containsKey(saved) ? saved : 'fr';
  }

  Future<void> setLanguage(String code) async {
    value = code;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString('language', code);
  }
}

/// Raccourci pratique : t('saisie', lang) → texte traduit, avec repli sur le
/// français si une clé venait à manquer dans une langue.
String t(String key, String lang) {
  return kTranslations[lang]?[key] ?? kTranslations['fr']![key] ?? key;
}
